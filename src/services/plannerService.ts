import { apiClient } from "./apiClient";

export interface PlannerMealSlot {
  _id?: string;
  slot: "Bữa Sáng" | "Bữa Trưa" | "Bữa Tối" | "Bữa Phụ";
  time: string;
  calories: number;
  isCooked: boolean;
  notes?: string;
  customTitle?: string;
  recipe?: {
    id: string;
    title: string;
    image: any;
    minutes: number;
    difficulty: string;
    calories: number;
    rating: number;
  };
}

export interface PlannerDay {
  dayOfWeek: string;
  date: string;
  dailyCalories: number;
  mealsCount: number;
  meals: PlannerMealSlot[];
}

export interface WeeklyPlanResponse {
  _id: string;
  weekStartDate: string;
  totalWeekCalories: number;
  days: PlannerDay[];
}

export interface ShoppingItemResponse {
  _id: string;
  id?: string;
  name: string;
  amount: string;
  price: number;
  category: string;
  recipeTitle?: string;
  bought: boolean;
  isAutoGenerated: boolean;
}

export interface ShoppingListResponse {
  weekStartDate: string;
  items: ShoppingItemResponse[];
  estimatedTotalCost: number;
  totalItemsCount: number;
  unboughtCount: number;
  boughtCount: number;
  fridgeItemsExcludedCount: number;
}

export const plannerService = {
  /**
   * Lấy kế hoạch bữa ăn 7 ngày tuần hiện tại
   * GET /api/v1/planner/current-week
   */
  getCurrentWeekPlan: async (weekDate?: string): Promise<WeeklyPlanResponse | null> => {
    try {
      const url = weekDate
        ? `/planner/current-week?weekDate=${weekDate}`
        : `/planner/current-week`;
      const res = await apiClient.get<{ data: WeeklyPlanResponse }>(url);
      return res.data?.data || (res.data as any);
    } catch (e) {
      console.warn("plannerService.getCurrentWeekPlan failed:", e);
      return null;
    }
  },

  /**
   * Thêm hoặc sửa món ăn vào một slot bữa ăn trong tuần
   * PUT /api/v1/planner/meals
   */
  setMealSlot: async (data: {
    weekDate?: string;
    dayOfWeek: string;
    slot: "Bữa Sáng" | "Bữa Trưa" | "Bữa Tối" | "Bữa Phụ";
    time?: string;
    recipeId?: string;
    customTitle?: string;
    calories?: number;
    isCooked?: boolean;
    notes?: string;
  }): Promise<WeeklyPlanResponse | null> => {
    try {
      const res = await apiClient.put<{ data: WeeklyPlanResponse }>(
        "/planner/meals",
        data
      );
      return res.data?.data || (res.data as any);
    } catch (e) {
      console.warn("plannerService.setMealSlot failed:", e);
      return null;
    }
  },

  /**
   * Tự động sinh danh mục đi chợ thông minh (đã trừ nguyên liệu sẵn có trong tủ lạnh)
   * GET /api/v1/planner/shopping-list
   */
  getSmartShoppingList: async (
    weekDate?: string
  ): Promise<ShoppingListResponse | null> => {
    try {
      const url = weekDate
        ? `/planner/shopping-list?weekDate=${weekDate}`
        : `/planner/shopping-list`;
      const res = await apiClient.get<{ data: ShoppingListResponse }>(url);
      return res.data?.data || (res.data as any);
    } catch (e) {
      console.warn("plannerService.getSmartShoppingList failed:", e);
      return null;
    }
  },

  /**
   * Cập nhật trạng thái đã mua (checkbox bought)
   * PATCH /api/v1/planner/shopping-list/:id/bought
   */
  toggleBoughtStatus: async (
    itemId: string,
    bought: boolean
  ): Promise<ShoppingItemResponse | null> => {
    try {
      const res = await apiClient.patch<{ data: ShoppingItemResponse }>(
        `/planner/shopping-list/${itemId}/bought`,
        { bought }
      );
      return res.data?.data || (res.data as any);
    } catch (e) {
      console.warn("plannerService.toggleBoughtStatus failed:", e);
      return null;
    }
  },

  /**
   * Thêm thủ công nguyên liệu vào giỏ đi chợ
   * POST /api/v1/planner/shopping-list
   */
  addCartItem: async (item: {
    name: string;
    amount?: string;
    price?: number;
    category?: string;
    recipeTitle?: string;
  }): Promise<ShoppingItemResponse | null> => {
    try {
      const res = await apiClient.post<{ data: ShoppingItemResponse }>(
        "/planner/shopping-list",
        item
      );
      return res.data?.data || (res.data as any);
    } catch (e) {
      console.warn("plannerService.addCartItem failed:", e);
      return null;
    }
  },

  /**
   * 1-Click Đồng bộ các nguyên liệu đã mua (bought: true) vào kho Tủ Lạnh
   * POST /api/v1/planner/sync-to-fridge
   */
  syncBoughtToFridge: async (): Promise<{
    syncedCount: number;
    syncedItems: any[];
    totalFridgeItems: number;
  } | null> => {
    try {
      const res = await apiClient.post<{ data: any }>(
        "/planner/sync-to-fridge"
      );
      return res.data?.data || (res.data as any);
    } catch (e) {
      console.warn("plannerService.syncBoughtToFridge failed:", e);
      return null;
    }
  },
};
